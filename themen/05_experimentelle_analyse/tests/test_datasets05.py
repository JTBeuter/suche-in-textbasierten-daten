def test_generator_reproduces_all_files_and_queries_with_local_rng(tmp_path):
    random.seed(9123)
    state = random.getstate()
    left, = build_datasets(synthetic_config(), tmp_path / "left")
    assert random.getstate() == state
    random.seed(5512)
    right, = build_datasets(synthetic_config(), tmp_path / "right")
    assert left["manifest"] == right["manifest"]
    assert left["queries"] == right["queries"]
    assert left["manifest"]["generator_version"] == GENERATOR_VERSION
    assert left["manifest"]["total_tokens"] == 200
    assert left["manifest"]["document_count"] == 2
    assert left["manifest"]["actual_vocabulary"] == 32
    assert left["manifest"]["file_order"] == ["d00000.txt", "d00001.txt"]
    assert set(left["manifest"]["parameters"]) >= {
        "documents", "length", "vocabulary", "seed", "distribution", "filler_guarantee",
        "repeated_run_length", "result_document_count", "serialization", "random_api",
    }
    for entry in left["manifest"]["files"]:
        payload = (left["root"] / entry["document_id"]).read_bytes()
        assert payload == (right["root"] / entry["document_id"]).read_bytes()
        assert hashlib.sha256(payload).hexdigest() == entry["sha256"]
        assert len(payload) == entry["bytes"]
        assert len(independent_tokens(payload.decode("utf-8"))) == entry["token_count"] == 100
    assert left["manifest"]["raw_bytes"] == sum(e["bytes"] for e in left["manifest"]["files"])
    query_bytes = (tmp_path / "left" / "small" / "queries.json").read_bytes()
    assert hashlib.sha256(query_bytes).hexdigest() == left["manifest"]["queries_sha256"]
    assert json.loads(query_bytes) == left["queries"]
    assert left["manifest"]["expected_tokens"] == {
        identifier: list(tokens) for identifier, tokens in left["expected_tokens"].items()
    }


def test_independent_unicode_examples_and_token_boundaries():
    # Explicit expected sequences, not generated by the productive tokenizer.
    text = "Straße STRASSE, Cafe\u0301; Ⅷ ² _ x\u0301.中文１２"
    expected = ("strasse", "strasse", "café", "x", "中文１２")
    assert independent_tokens(text) == expected
    assert tokenize(text) == expected


def test_planted_queries_include_all_overlaps_and_known_absences(tmp_path):
    dataset, = build_datasets(synthetic_config(), tmp_path)
    queries = {q["id"].split("small:", 1)[1]: q for q in dataset["queries"]}
    ids = ["d00000.txt", "d00001.txt"]
    assert queries["word:frequent:k1"]["expected"] == ids
    assert queries["word:frequent:k1"]["cf"] == [4]
    assert queries["word:rare:k1"]["cf"] == [2]
    assert queries["word:missing:k1"]["expected"] == []
    for length in (1, 2, 3, 5):
        frequent = queries[f"phrase:frequent:k{length}"]
        repeated = queries[f"phrase:repeated:k{length}"]
        assert frequent["expected"] == {identifier: [0, 50] for identifier in ids}
        assert repeated["expected"] == {identifier: list(range(20, 27 - length)) for identifier in ids}
        assert repeated["position_count"] == 2 * (7 - length)
        assert queries[f"phrase:rare:k{length}"]["expected"] == {identifier: [30] for identifier in ids}
        assert queries[f"phrase:missing:k{length}"]["expected"] == {}
    for length in (2, 3, 5):
        assert queries[f"phrase:wrong_order:k{length}"]["expected"] == {}
        for kind in ("and", "or"):
            assert queries[f"{kind}:frequent:k{length}"]["expected"] == ids
        assert queries[f"and:missing:k{length}"]["expected"] == []
        assert queries[f"or:missing:k{length}"]["expected"] == ids
    assert len({q["id"] for q in dataset["queries"]}) == len(dataset["queries"])


def test_hand_calculated_reference_handles_boolean_and_phrase_boundaries():
    tokens = {"b.txt": ("a", "b", "a", "a", "a"), "a.txt": ("b", "a")}
    assert expected_result(tokens, "word", ["a"]) == ["a.txt", "b.txt"]
    assert expected_result(tokens, "and", ["a", "b"]) == ["a.txt", "b.txt"]
    assert expected_result(tokens, "and", ["a", "missing"]) == []
    assert expected_result(tokens, "or", ["b", "missing"]) == ["a.txt", "b.txt"]
    assert expected_result(tokens, "phrase", ["a", "a"]) == {"b.txt": [2, 3]}
    assert expected_result(tokens, "phrase", ["a", "b", "b", "a"]) == {}
    with pytest.raises(ValueError):
        expected_result(tokens, "phrase", [])


def test_real_snapshot_and_independent_plan_preserve_pinned_files(tmp_path):
    real = REPOSITORY / "daten/real/kafka_verwandlung"
    manifest, token_plan = verify_real_snapshot(real)
    assert manifest["source_sha256"] == "359d3f5983c812393f4bd7ee49a350ffffc7d476015e58d6b84b6c848dd2b0e9"
    assert len(token_plan["01_anfang.txt"]) == 1271
    before = {path.name: path.read_bytes() for path in real.iterdir() if path.is_file()}
    dataset, = build_datasets({"schema_version": 1, "datasets": [{
        "id": "kafka", "kind": "real", "path": "daten/real/kafka_verwandlung",
    }]}, tmp_path)
    assert dataset["root"] == tmp_path / "kafka/corpus"
    assert {path.name: path.read_bytes() for path in dataset["root"].iterdir()} == before
    assert dataset["manifest"]["source_manifest"] == manifest
    assert dataset["manifest"]["total_tokens"] == 1271
    assert dataset["manifest"]["raw_bytes"] == 8495
    assert before == {path.name: path.read_bytes() for path in real.iterdir() if path.is_file()}
    repeated = next(q for q in dataset["queries"] if q["category"] == "repeated")
    assert repeated["terms"] == ["gregor", "gregor"]
    assert repeated["expected"] == {"01_anfang.txt": [1060, 1078]}
    rare = next(q for q in dataset["queries"] if q["kind"] == "word" and q["category"] == "rare")
    assert rare["terms"] == ["fenster"] and rare["cf"] == [1]


@pytest.mark.parametrize("damaged", ["source", "excerpt", "extra_file"])
def test_real_snapshot_rejects_damage(tmp_path, damaged):
    target = tmp_path / "real"
    shutil.copytree(REPOSITORY / "daten/real/kafka_verwandlung", target)
    if damaged == "source":
        (target / "quelle.pg").write_bytes(b"changed archive")
    elif damaged == "excerpt":
        (target / "01_anfang.txt").write_bytes(b"changed excerpt")
    else:
        (target / "additional.txt").write_bytes(b"undocumented file")
    with pytest.raises(ValueError):
        verify_real_snapshot(target)


@pytest.mark.parametrize("field,value", [
    ("documents", 1), ("length", 101), ("vocabulary", 16),
    ("vocabulary", 99999), ("seed", True), ("length", 100.0),
])
def test_invalid_synthetic_parameters_fail_before_output(tmp_path, field, value):
    config = synthetic_config()
    config["datasets"][0][field] = value
    with pytest.raises(ValueError):
        build_datasets(config, tmp_path / "invalid")
    assert not (tmp_path / "invalid").exists()


def test_duplicate_pathlike_ids_and_reused_target_fail(tmp_path):
    config = synthetic_config()
    config["datasets"].append(deepcopy(config["datasets"][0]))
    with pytest.raises(ValueError, match="duplicate"):
        build_datasets(config, tmp_path)
    config = synthetic_config()
    config["datasets"][0]["id"] = "../outside"
    with pytest.raises(ValueError, match="dataset id"):
        build_datasets(config, tmp_path)
    build_datasets(synthetic_config(), tmp_path)
    with pytest.raises(ValueError, match="already exists"):
        build_datasets(synthetic_config(), tmp_path)


