def test_manifest_and_query_bytes_reproduce_across_python_hash_seeds(tmp_path):
    config_path = tmp_path / "config.json"
    config_path.write_text(json.dumps(synthetic_config()), encoding="utf-8")
    targets = [tmp_path / "hash1", tmp_path / "hash9"]
    for target, hash_seed in zip(targets, ("1", "9"), strict=True):
        subprocess.run([
            sys.executable, "-m", "experimentelle_analyse", "generate",
            "--config", str(config_path), "--output", str(target),
        ], cwd=REPOSITORY, env={**os.environ, "PYTHONHASHSEED": hash_seed},
            check=True, capture_output=True, text=True)
    for relative in ("small/manifest.json", "small/queries.json",
                     "small/corpus/d00000.txt", "small/corpus/d00001.txt"):
        assert (targets[0] / relative).read_bytes() == (targets[1] / relative).read_bytes()


